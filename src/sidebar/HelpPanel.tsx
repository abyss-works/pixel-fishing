// 도움말 콘텐츠 — Sidebar의 '도움말' 탭에서 렌더.
//
// **맨 위 넉 줄만 항상 보이고 나머지는 접어 둔다.** 전부 펼쳐 두니 "글이 너무 길다"는 말이
