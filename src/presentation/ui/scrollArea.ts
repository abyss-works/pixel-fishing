// 창 안 세로 스크롤 칸의 공용 클래스. 막대는 6px 흰 막대(pf-scroll-panel)이고, 막대 자리는 늘 확보하며(scrollbar-gutter)
// 내용과 막대 사이에 8px 여백(pr-2)을 둔다. 막대가 나타나도 내용 폭이 흔들리지 않고 내용이 막대에 붙지 않는다.
// 왼쪽, 위, 아래는 안쪽 여백 4px을 주고 같은 만큼 바깥 여백(음수)으로 되돌린다. 내용 위치와 내용 높이로 커지는 칸의 높이는 그대로이면서
// 첫 열과 첫 줄, 마지막 줄의 포커스 윤곽(바깥 3px)이 스크롤 칸 경계에서 잘리지 않는다.
// 칸 높이와 모양은 호출부가 정한다. 틀(Inset, Frame)이 자기 안쪽 여백을 가지면 틀은 두고 그 안에 이 칸을 둔다.
// 막대를 숨기는 칸(pf-scroll)은 이 규칙의 예외라 여기에 두지 않는다.
const SCROLL_Y_BASE = 'pf-vscroll pf-scroll-panel [scrollbar-gutter:stable] -ml-1 pl-1 -mt-1 pt-1 pr-2';

/** 높이를 정하지 않거나 화면 높이 같은 여유 상한(max-h)만 두는 칸. 내용 높이로 커질 때 안쪽 여백이 높이를 늘리지 않는다 */
export const SCROLL_Y = `${SCROLL_Y_BASE} -mb-1 pb-1`;

/** 보이는 줄 수로 높이를 정하는 칸(h, max-h). 위쪽은 안쪽 여백 4px을 바깥 여백으로 되돌리고, 아래쪽 안쪽 여백 4px은 바깥으로 되돌리지 않는다.
 *  칸 높이는 위 여백 4px + 정한 줄들 + 아래 여백 4px로 정한다. 쉬는 상태(맨 위)에서 아래 여백 자리는 줄 사이 간격(4px 이상)이 비치는 자리라
 *  다음 줄이 보이지 않고, 마지막 줄의 포커스 윤곽(바깥 3px)은 아래 여백 안에 들어가 잘리지 않는다.
 *  줄 사이 간격이 없는 표는 아래 여백을 높이에 넣지 않고(위 여백 4px + 줄들) 쓴다. 이때는 맨 끝에서 마지막 줄 아래에 여백이 생긴다.
 *  내용이 칸보다 긴 목록에 쓰고, 내용이 칸보다 낮으면 칸 높이는 내용 + 아래 여백 4px이다. */
export const SCROLL_Y_ROWS = `${SCROLL_Y_BASE} pb-1`;
