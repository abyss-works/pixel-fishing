-- 0035 되돌리기. auth.supabase_users를 빈 표로 다시 만든다. 열은 0021이 이름을 바꿔 남긴 표(Supabase 덤프의 auth.users, 생성 열 confirmed_at 제외)와 같다.
-- 지운 데이터는 복구되지 않는다. 데이터가 필요하면 롤백보다 먼저 백업에서 복구한다.
-- 이 표가 있어야 0021.down이 이어진다.
create table if not exists auth.supabase_users (
  instance_id uuid,
  id uuid primary key,
  aud character varying,
  role character varying,
  email character varying,
  encrypted_password character varying,
  email_confirmed_at timestamptz,
  invited_at timestamptz,
  confirmation_token character varying,
  confirmation_sent_at timestamptz,
  recovery_token character varying,
  recovery_sent_at timestamptz,
  email_change_token_new character varying,
  email_change character varying,
  email_change_sent_at timestamptz,
  last_sign_in_at timestamptz,
  raw_app_meta_data jsonb,
  raw_user_meta_data jsonb,
  is_super_admin boolean,
  created_at timestamptz,
  updated_at timestamptz,
  phone text,
  phone_confirmed_at timestamptz,
  phone_change text,
  phone_change_token character varying,
  phone_change_sent_at timestamptz,
  email_change_token_current character varying,
  email_change_confirm_status smallint,
  banned_until timestamptz,
  reauthentication_token character varying,
  reauthentication_sent_at timestamptz,
  is_sso_user boolean not null default false,
  deleted_at timestamptz,
  is_anonymous boolean not null default false
);
